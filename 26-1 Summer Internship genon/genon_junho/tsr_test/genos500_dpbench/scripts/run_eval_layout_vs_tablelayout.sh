#!/usr/bin/env bash
# Genos-500 dp-bench evaluation wrapper for the README report table.
#
# It evaluates:
#   - chandra_layout
#   - chandra_tablelayout
# and, optionally, dots_ocr if DOTS_PRED exists or is provided.
#
# Required inputs:
#   1) dp-bench GT JSON: REF
#   2) Genos-500 page images: IMAGES_DIR
#   3) Chandra inference outputs: LAYOUT_JSONL, TABLELAYOUT_JSONL
#
# The Chandra predictions are first converted from predictions_unified.jsonl
# into dp-bench prediction JSON, then evaluated with bbox table matching.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PYTHON="${PYTHON:-python3}"

# b200 default project root. Override this when running elsewhere.
TSR_VLM_ROOT="${TSR_VLM_ROOT:-/NHNHOME/WORKSPACE/0426030039_A/jhshin/tsr_test/train/vlm}"

# GT and image size source. REF is intentionally not committed; copy it from the
# task/272 recovery artifact or keep it in this local path.
REF="${REF:-${ROOT}/genos-500-set/reference_dp_bench.json}"
IMAGES_DIR="${IMAGES_DIR:-${TSR_VLM_ROOT}/eval_data/500_genos_val_set/images}"

# Chandra inference outputs generated by train/vlm/scripts/wait_train_and_infer_genos500_ocr.sh.
LAYOUT_JSONL="${LAYOUT_JSONL:-${TSR_VLM_ROOT}/eval_results/genos500_ocr_layout/predictions_unified.jsonl}"
# The README/report metric table is reproduced from genos500_ocr_tablelayout_epoch3.
# To evaluate another checkpoint/output, override TABLELAYOUT_JSONL explicitly.
TABLELAYOUT_JSONL="${TABLELAYOUT_JSONL:-${TSR_VLM_ROOT}/eval_results/genos500_ocr_tablelayout_epoch3/predictions_unified.jsonl}"

# Optional dots.ocr baseline in dp-bench pred JSON format. Set RUN_DOTS=false to skip.
RUN_DOTS="${RUN_DOTS:-true}"
DOTS_PRED="${DOTS_PRED:-${ROOT}/dp_out/eval_excluded_8docs_v2/dots_ocr/pred_dp_bench_full.json}"
DOTS_OUT_DIR="${DOTS_OUT_DIR:-${ROOT}/dp_out/eval_excluded_8docs_v2/dots_ocr}"

# Output directories under local genos500_dpbench.
CHANDRA_OUT_ROOT="${CHANDRA_OUT_ROOT:-${ROOT}/dp_out/genos500_chandra_ocr_20260623}"
LAYOUT_OUT_DIR="${CHANDRA_OUT_ROOT}/layout"
TABLELAYOUT_OUT_DIR="${CHANDRA_OUT_ROOT}/tablelayout"

require_file() {
  local label="$1"
  local path="$2"
  if [[ ! -f "${path}" ]]; then
    echo "[ERROR] ${label} not found: ${path}" >&2
    exit 1
  fi
}

require_dir() {
  local label="$1"
  local path="$2"
  if [[ ! -d "${path}" ]]; then
    echo "[ERROR] ${label} not found: ${path}" >&2
    exit 1
  fi
}

run_eval() {
  local model="$1"
  local pred="$2"
  local out_dir="$3"
  local pred_coord_space="$4"
  local pred_grid="$5"

  mkdir -p "${out_dir}"
  local result="${out_dir}/eval_result_gitlab.txt"

  {
    echo "model : ${model}"
    echo "pred  : ${pred}"
    echo "ref   : ${REF}"
    echo "images_dir : ${IMAGES_DIR}"
    echo "table_match_mode : bbox (iou_thr=0.5)"
    echo "coord : gt=image pred=${pred_coord_space} pred_grid=${pred_grid}"
    echo "nid_convert_table_text : false"
    echo "=============================="

    "${PYTHON}" "${ROOT}/upstage-dp-bench/evaluate.py" \
      --ref_path "${REF}" \
      --pred_path "${pred}" \
      --mode layout

    echo "------------------------------"
    echo "--- unmatched_gt=zero (b) ---"
    "${PYTHON}" "${ROOT}/upstage-dp-bench/evaluate.py" \
      --ref_path "${REF}" \
      --pred_path "${pred}" \
      --mode table \
      --table_match_mode bbox \
      --table_bbox_unmatched_gt zero \
      --table_bbox_iou_thr 0.5 \
      --gt_coord_space image \
      --pred_coord_space "${pred_coord_space}" \
      --pred_grid "${pred_grid}" \
      --images_dir "${IMAGES_DIR}"

    echo "------------------------------"
    echo "--- unmatched_gt=skip (a) ---"
    "${PYTHON}" "${ROOT}/upstage-dp-bench/evaluate.py" \
      --ref_path "${REF}" \
      --pred_path "${pred}" \
      --mode table \
      --table_match_mode bbox \
      --table_bbox_unmatched_gt skip \
      --table_bbox_iou_thr 0.5 \
      --gt_coord_space image \
      --pred_coord_space "${pred_coord_space}" \
      --pred_grid "${pred_grid}" \
      --images_dir "${IMAGES_DIR}"
  } | tee "${result}"

  echo "[done] ${model} -> ${result}"
}

main() {
  require_file "REF" "${REF}"
  require_dir "IMAGES_DIR" "${IMAGES_DIR}"
  require_file "LAYOUT_JSONL" "${LAYOUT_JSONL}"
  require_file "TABLELAYOUT_JSONL" "${TABLELAYOUT_JSONL}"

  mkdir -p "${LAYOUT_OUT_DIR}" "${TABLELAYOUT_OUT_DIR}"

  echo "[convert] chandra_layout predictions_unified.jsonl -> dp-bench pred JSON"
  "${PYTHON}" "${ROOT}/scripts/prepare/convert_qwen_pred_to_dpbench.py" \
    --input "${LAYOUT_JSONL}" \
    --output "${LAYOUT_OUT_DIR}/pred_dp_bench_full.json"

  echo "[convert] chandra_tablelayout predictions_unified.jsonl -> dp-bench pred JSON"
  "${PYTHON}" "${ROOT}/scripts/prepare/convert_qwen_pred_to_dpbench.py" \
    --input "${TABLELAYOUT_JSONL}" \
    --output "${TABLELAYOUT_OUT_DIR}/pred_dp_bench_full.json"

  if [[ "${RUN_DOTS}" == "true" ]]; then
    if [[ -f "${DOTS_PRED}" ]]; then
      run_eval "dots_ocr" "${DOTS_PRED}" "${DOTS_OUT_DIR}" "fraction_bl" "1024"
    else
      echo "[warn] RUN_DOTS=true but DOTS_PRED does not exist. Skip dots_ocr: ${DOTS_PRED}" >&2
    fi
  fi

  run_eval "chandra_layout" "${LAYOUT_OUT_DIR}/pred_dp_bench_full.json" "${LAYOUT_OUT_DIR}" "grid" "1000"
  run_eval "chandra_tablelayout" "${TABLELAYOUT_OUT_DIR}/pred_dp_bench_full.json" "${TABLELAYOUT_OUT_DIR}" "grid" "1000"

  echo ""
  echo "Summary lines:"
  for f in \
    "${DOTS_OUT_DIR}/eval_result_gitlab.txt" \
    "${LAYOUT_OUT_DIR}/eval_result_gitlab.txt" \
    "${TABLELAYOUT_OUT_DIR}/eval_result_gitlab.txt"; do
    [[ -f "${f}" ]] || continue
    echo ""
    echo "## ${f#${ROOT}/}"
    grep -E "NID Score|bbox-match|TEDS Score|TEDS-S Score" "${f}" || true
  done
}

main "$@"
