# -*- coding: utf-8 -*-
"""
app/llm/prompt_templates.py

LLM에 보낼 프롬프트를 구성하는 모듈.

- 한국어 계약서를 입력으로 받아
- 특정 필드들을 JSON으로 추출해 달라고 지시한다.
"""

from textwrap import dedent


def _get_prompt_parts() -> tuple:
    """
    프롬프트의 instruction과 example 부분을 반환합니다.
    (오버헤드 계산용)
    """
    instruction = dedent("""
    <instruction>
    당신은 한국어 계약서에서 핵심 메타데이터를 추출하는 법률전문가이자 계약 분석가입니다.
    
    추출할 필드 (JSON 키는 영문 고정, 날짜는 YYYYMMDD 형식, 모르는 값은 null):
    
    - CNT_NAME: 계약 이름(제목). 예: "서비스 이용 계약서", "임대차계약서"
      **중요: 계약명 추출 시 두 가지 소스를 확인하되, 확실한 경우에만 각각 추출하세요:**
      
      1. 제목 영역(상단 타이틀): 
         - 1페이지 최상단 1-5줄에 표시된 계약서의 공식 제목
         - 보통 큰 글씨나 굵은 글씨로 강조되어 있음
         - "계약서", "계약", "Agreement" 등의 단어가 포함된 경우가 많음
         - 일반적인 계약서 종류를 나타내는 제목 (예: "[업종] 계약서", "[계약 유형] 계약서")
      
      2. 라벨 영역(세부 계약명):
         - "계약명:", "계약제목:", "계약서명:", "1. 계약명:" 등의 라벨과 함께 **명확하게** 명시된 세부 계약명만 추출
         - 보통 제목 영역 바로 아래나 본문 초반에 위치
         - 해당 계약의 구체적인 이름이나 프로젝트명을 나타냄
         - **중요: 라벨 영역 값이 명확하지 않거나 제목과 동일하거나, 제목의 일부분만 반복하는 경우라면 추출하지 마세요.**
         - 억지로 부제목을 찾아내려고 하지 말고, 확실하게 별도의 세부 계약명이 있을 때만 사용하세요.
      
      **추출 규칙:**
      - 제목만 있는 경우 → CNT_NAME: "제목"
      - 제목과 라벨이 모두 있고 서로 **명백히 다르고 확실한** 경우 → CNT_NAME: "제목_라벨" (언더스코어로 연결)
      - 제목만 있거나 라벨 영역이 명확하지 않으면 → CNT_NAME: "제목"
      
      **라벨 추출 시 주의사항:**
      - 애매한 경우 → 라벨을 무시하고 제목만 사용하세요
      - 제목과 라벨이 거의 동일하거나 중복되면 → 제목만 사용하세요
    
    - CNT_CON_DATE: 계약 체결일(서명일). 명시적 선언 → 서명란 날짜 → 전문 날짜 순으로 확인.
    

    - CNT_ST_DATE: 계약 시작일(유효기간 시작). YYYYMMDD 형식.
      1. **명시적 날짜 우선**: 계약서 내 "계약 시작일", "효력 발생일", "기간은 ~부터" 등의 키워드와 함께 기재된 구체적인 날짜를 최우선으로 추출하세요.
      2. **체결일 대체 (Fallback)**: 
        - 명시된 시작일이 없는 경우
        - 시작 기준이 '미확정 사건'(예: 퇴사일, 사망일, 조건 달성 시 등)인 경우
        위 두 경우에는 **체결일(CNT_CON_DATE)**을 시작일로 간주하여 사용하세요.

    - CNT_END_DATE: 계약 종료일(유효기간 끝). YYYYMMDD 형식 또는 null.
      1. **명시적 날짜**: "만료일", "YYYY년 MM월 DD일까지" 등 종료 날짜가 명시된 경우 해당 값을 추출하세요.
      2. **[핵심] 기간 기준점(Base Point) 확인**: 
        - 종료일이 기간(예: "1년", "24개월")으로 제시된 경우, 그 기간이 **언제부터 시작되는지(기준점)**를 반드시 확인하세요.
        - **계산 가능**: 기준점이 "체결일로부터", "계약 시작일로부터", "효력 발생일로부터"인 경우에만 [기준일 + 기간]을 계산하세요.
        - **계산 금지 (NULL)**: 기준점이 **"퇴사 후", "해지 후", "사고 발생 시", "만료 후"** 등 미확정 사건인 경우, **절대로 시작일(CNT_ST_DATE)에 기간을 더하지 말고 무조건 null로 처리하세요.**
          (예: "근무 기간은 물론 퇴사 후 1년까지" → 기준점이 '퇴사'이므로 null)
      3. **기타**: 자동 갱신 조항만 있거나 기간 언급이 없는 경우 **null**을 반환하세요.
    

    - CNT_RENEWAL: 재계약 문서인지 여부. 이전 계약을 대체/갱신하는 재체결 계약이면 "O", 아니면 "X".
    
    - CNT_AMT: 계약 총액 정보 객체.
      **단순 문자열이 아닌, 아래 4개 필드를 가진 JSON 객체로 출력하세요.**
      {
        "value": "수식 문자열 또는 숫자 문자열 (계산 불가능하면 null)",
        "confidence": 0.0 ~ 1.0 사이의 실수 (1.0: 명시적 찾음, 0.9: 확실한 계산, 0.5 미만: 불확실)",
        "note": "상태 코드 (explicit / calculated / uncertain / not_found)",
        "llm_reason": "다음 6단계 분석 결과를 요약: 1) 변수 추출 2) 지급횟수 계산 3) 명시 총액 4) 계산식 5) 검증 6) 결과"
      }
      
      <thinking> 단계에서 다음 [논리적 검증 프로세스]를 반드시 수행하세요 (순서 중요):
      
      **[최우선] 1) 명시 총액 확인: 계약서 전체에서 직접 명시된 총액을 먼저 찾으세요.**
         - 키워드: "계약금액", "계약 금액", "총액", "총 금액", "총 계약금액", "총 공사금액", "총 공급가액", "총 대가", "전체 금액"
         - 영문: "Contract Amount", "Total Amount", "Contract Value", "Total Contract Value"
         - 문맥: "~로 한다", "~로 정한다", "~로 한다" 등의 확정적 표현이 있는 금액
         - 매우 명확한 명시 총액이 있으면 그것을 사용하고, 계산 단계는 생략하세요. (confidence: 1.0, note: "explicit")
      
      2) 변수 추출: 명시 총액이 없을 때만, 일시금(보증금, 선입금 등), 정기지급액, 지급주기(월/분기/반기/연), 계약기간(시작일~종료일) 등 계약서 곳곳에 흩어진 숫자들을 찾아 정리
      
      3) 지급횟수 계산: 정기지급 구조가 있을 때만 수행
         - 계약기간을 개월수로 정확히 계산 (종료일 - 시작일)
         - 지급주기 확인: 일, 주(7일), 월(1개월), 분기(3개월), 반기(6개월), 연(12개월 or 52주) 등
         - 지급횟수 = (계약기간 개월수) / (지급주기 개월수)
         - 예: 36개월 계약, 분기 지급 → 36 / 3 = 12번
         - 주의: 기간이 확정되지 않으면 계산하지 마세요
      
      4) 계산식 작성: 변수들로 총액 계산이 가능한 경우에만 수행
         - 일시금 + (정기지급액 × 지급횟수) 형태만 사용
         - 비율 역산: 보증금이 총액의 N%인 경우에만 역산
         - 숫자와 연산자(+, -, *, /, 괄호)만 포함
         - 여러 계산 방식이 가능하면, 가장 확실한 하나만 선택
         - "또는", "~중 선택", "최소~", "최대~" 같은 불확정 표현이 있으면 null
         - 변수명이나 미확정 값이 포함된 경우 null 반환
      
      5) 검증 및 결과 선택:
         - 명백한 명시 총액이 있으면: 그 값을 사용 (최우선)
         - 명백한 명시 총액이 없고 계산식만 있으면: 계산식 사용
         - 둘 다 없거나 불확실하면: null
         - 명시 총액과 계산 결과가 다르면: 명시 총액 우선, llm_reason에 "CONFLICT: 명시 총액 우선 사용" 명시
      
      6) llm_reason 작성: 각 단계별 결과를 명확히 요약
         - 형식: "1) 명시 총액: [찾음/없음 및 내용] | 2) 변수: [목록] | 3) 지급횟수: [계산 결과] | 4) 계산식: [수식 또는 null] | 5) 검증: [결과] | 6) 최종: [선택한 값 및 근거]"
      
      **중요: 
      - 명시 총액을 최우선으로 찾고, 있으면 계산하지 마세요.
      - value 필드에는 숫자만 또는 숫자와 연산자만 포함된 하나의 수식을 반환하세요.
      - 한글, 변수명, "또는" 같은 선택 표현을 포함하면 null로 반환됩니다.**
    
    - CNT_AMT_CRY: 계약 금액 통화. KRW, USD, JPY, EUR 중 하나. 원/₩ → KRW, 달러/$ → USD. 알 수 없으면 "KRW".
    
    - CNT_AUTO_RNW_TERM_NUM: 자동갱신 주기의 기간 숫자.
      자동갱신: 계약 기간이 끝났을 때 별도 동의/서명 없이 자동으로 다음 기간으로 연장되는 것.
      자동갱신 주기: 계약이 자동으로 연장되는 간격(주기).
      예: "1년 단위로 자동갱신", "6개월마다 자동 연장" → 숫자: 1 또는 6. 없으면 null.
    
    - CNT_AUTO_RNW_TERM_UNIT: 자동갱신 주기의 기간 단위.
      "연", "년" → "YEAR", "개월", "달" → "MONTH", "일" → "DAY". 없으면 null.
    
    <thinking> 태그로 추론 과정을 기술한 후 <result> 태그로 JSON을 출력하세요.
    </instruction>
    """)
    
    example = dedent("""
    <example>
    <thinking>
    - 제목: "물품 공급 계약서" (1페이지 상단)
    - 체결일: "계약일: 2024년 1월 15일" → 20240115
    - 시작일: "2024년 2월 1일부터" → 20240201
    - 종료일: "2026년 1월 31일까지" → 20260131
    - 금액 분석:
      1) 명시 총액: 제2조 "본 계약의 총 계약금액은 금 3억원으로 한다" → 300000000 찾음 (최우선)
      2) 변수 추출: (명시 총액 있으므로 생략)
      3) 지급횟수 계산: (명시 총액 있으므로 생략)
      4) 계산식: (명시 총액 있으므로 생략)
      5) 검증: 명시 총액 사용
      6) 최종: 명시 총액 300000000 사용
    - 재계약: "갱신" 표현 없음 → "X"
    - 자동갱신: 조항 없음 → null
    </thinking>
    
    <result>
    {
      "CNT_NAME": "물품 공급 계약서",
      "CNT_CON_DATE": "20240115",
      "CNT_ST_DATE": "20240201",
      "CNT_END_DATE": "20260131",
      "CNT_RENEWAL": "X",
      "CNT_AMT": {
        "value": "300000000",
        "confidence": 1.0,
        "note": "explicit",
        "llm_reason": "1) 명시 총액: 제2조에서 '총 계약금액 3억원' 찾음 | 2) 변수: (생략) | 3) 지급횟수: (생략) | 4) 계산식: (생략) | 5) 검증: 명시 총액 사용 | 6) 최종: 300000000 (명시 총액)"
      },
      "CNT_AMT_CRY": "KRW",
      "CNT_AUTO_RNW_TERM_NUM": null,
      "CNT_AUTO_RNW_TERM_UNIT": null
    }
    </result>
    </example>
    """)
    
    final_instruction = "\n위 <contract> 태그의 계약서를 분석하여, <thinking> 태그로 추론 과정을 기술한 후 <result> 태그로 JSON을 출력하세요."
    
    return instruction, example, final_instruction


def estimate_prompt_overhead() -> int:
    """
    프롬프트 오버헤드(instruction + example + 마지막 지시문 등)의 대략적인 길이를 계산합니다.
    contract_text가 아닌 부분의 길이입니다.
    
    Returns:
        int: 대략적인 오버헤드 길이 (자)
    """
    # 실제 오버헤드 계산은 _get_prompt_parts() 결과를 사용
    instruction, example, final_instruction = _get_prompt_parts()
    
    # 빈 contract_text로 오버헤드 계산
    empty_contract = """
<contract>
</contract>
"""
    
    overhead_prompt = (
        instruction
        + "\n\n"
        + example
        + "\n\n"
        + empty_contract
        + "\n\n"
        + final_instruction
    )
    
    return len(overhead_prompt)


def build_full_fields_prompt(contract_text: str) -> str:
    """
    계약서 전체(or 일부) 텍스트를 받아 LLM용 프롬프트를 만든다.
    
    Chain of Thought (CoT)와 XML 태그 구조를 활용하여 정확도와 일관성을 향상시킨 프롬프트를 생성합니다.

    Args:
        contract_text: 페이지/라인 정보가 포함된 계약서 텍스트

    Returns:
        str: LLM에 보낼 프롬프트
    """
    instruction, example, final_instruction = _get_prompt_parts()
    
    contract = f"""
<contract>
{contract_text}
</contract>
"""
    
    prompt = (
        instruction
        + "\n\n"
        + example
        + "\n\n"
        + contract
        + "\n\n"
        + final_instruction
    )
    
    return prompt
  